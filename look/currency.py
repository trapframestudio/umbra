"""
Umbra's currency is the hryvnia, not the ruble.

    python3 currency.py          write the string overrides into out/full
    python3 currency.py --show   list every change instead

The user: "swap in something that isn't rubles". The Zone is in Ukraine.

- Art: ui.py letters a hryvnia sign over the ruble sign baked into the money
  box and trade bars.
- Money read-outs: G.A.M.M.A.'s scripts glue a literal " RU" onto amounts.
  xrRazom already rewrites those at display time to its st_xrr_currency
  string ("UAH"), so we leave them to it and never touch its files.
- Prose: about 200 English and 300 Russian dialogue and task lines say RU,
  rubles or руб. Those are overridden here. The engine reads each language's
  text files in name order and a later definition of a string id replaces
  the earlier one (CStringTable::Load). So one file whose name sorts last,
  zzzzzzzz_umbra_currency.xml, holds just those strings: the winning text
  with only the currency changed. English uses UAH, as xrRazom does, and
  "hryvnias". Russian uses грн and the гривна forms.

Russian only swaps the currency's own word forms: many other words start
with "руб" (рубеж, рубильник, рубашка, the stalker Рубец, ...).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import vfs  # noqa: E402

MOD = os.path.join(HERE, "out", "full")
NAME = "zzzzzzzz_umbra_currency.xml"     # sorts after G.A.M.M.A.'s zzzz_ and xrRazom's zzzzzz_

_EN_WORDS = {"ruble": "hryvnia", "rubles": "hryvnias", "rouble": "hryvnia", "roubles": "hryvnias"}

# рубль (m.) -> гривна (f.), case by case; руб(.) -> грн(.)
_RU_WORDS = {
    "рубль": "гривна", "рубля": "гривны", "рублю": "гривне", "рублём": "гривной", "рублем": "гривной",
    "рубле": "гривне", "рубли": "гривны", "рублей": "гривен", "рублям": "гривнам", "рублями": "гривнами",
    "рублях": "гривнах", "руб": "грн",
    "рублевый": "гривневый", "рублёвый": "гривневый", "рублевых": "гривневых", "рублёвых": "гривневых",
    "рублевые": "гривневые", "рублёвые": "гривневые",
}
_CYR = "А-Яа-яЁёІіЇїЄєҐґ"


def _case(word, new):
    return new[0].upper() + new[1:] if word[0].isupper() else new


def english(text):
    text = re.sub(r"\bRU\b", "UAH", text)
    return re.sub(r"\b(rubles?|roubles?)\b",
                  lambda m: _case(m.group(1), _EN_WORDS[m.group(1).lower()]), text, flags=re.I)


# гривна is feminine where рубль is masculine: the words that agree with it
# (checked against every changed line with --show)
_RU_AGREE = [(r"\b([Дд])ва гривны", r"\1ве гривны"),
             (r"\b([Оо])дин гривна", r"\1дна гривна"),
             (r"\bэлектронный гривна", "электронная гривна")]


def russian(text):
    text = re.sub(r"\bRU\b", "UAH", text)

    def swap(m):
        w = m.group(0)
        new = _RU_WORDS.get(w.lower())
        return _case(w, new) if new else w
    text = re.sub(r"(?<![%s])[%s]+" % (_CYR, _CYR), swap, text)
    for pat, rep in _RU_AGREE:
        text = re.sub(pat, rep, text)
    return text


LANGS = {"eng": english, "rus": russian}


def strings(lang):
    """{id: text} as the game ends up with them for `lang` (raw XML text,
    entities and all), in the order files load."""
    c = vfs.VFS(prefix="configs/text/")
    files = []
    for rel, src in c.winners("configs/text/%s/" % lang).items():
        name = rel.rsplit("/", 1)[-1]
        if rel.count("/") == 3 and name.lower().endswith(".xml") and name.lower() != NAME:
            files.append((name.lower(), src))
    final = {}
    for _, src in sorted(files, key=lambda f: f[0]):
        # surrogateescape keeps bytes cp1251 can't map (0x98) exactly as they were
        t = src.read().decode("cp1251", "surrogateescape")
        t = re.sub(r"<!--.*?-->", "", t, flags=re.S)
        for m in re.finditer(r'<string\s+id="([^"]+)"\s*>\s*<text>(.*?)</text>', t, re.S):
            final[m.group(1)] = m.group(2)
    return final


def changes(lang):
    fix = LANGS[lang]
    out = {}
    for sid, text in strings(lang).items():
        new = fix(text)
        if new != text:
            out[sid] = (text, new)
    return out


def build(show=False):
    for lang in LANGS:
        ch = changes(lang)
        if show:
            for sid, (old, new) in sorted(ch.items()):
                print("[%s] %s\n   - %s\n   + %s" % (lang, sid, old.strip()[:160], new.strip()[:160]))
            continue
        body = "".join('\t<string id="%s">\n\t\t<text>%s</text>\n\t</string>\n' % (sid, new)
                       for sid, (_, new) in sorted(ch.items()))
        xml = ('<?xml version="1.0" encoding="windows-1251" ?>\n'
               "<!-- Umbra: the currency is the hryvnia. Generated by look/currency.py from the\n"
               "     strings G.A.M.M.A. ships (only the currency changed); don't edit by hand. -->\n"
               "<string_table>\n%s</string_table>\n" % body)
        out = os.path.join(MOD, "gamedata", "configs", "text", lang, NAME)
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "wb") as f:
            f.write(xml.encode("cp1251", "surrogateescape"))
        print("%s: %d strings -> %s" % (lang, len(ch), out))


if __name__ == "__main__":
    build(show="--show" in sys.argv)
